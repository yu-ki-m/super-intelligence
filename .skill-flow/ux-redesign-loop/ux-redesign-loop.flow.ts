//
// 実行環境が提供する能力:
//   shell.exec         … コマンドを実行し、終了コード・標準出力・標準エラーを手を加えずに返す
//   file.read          … ファイルを読む・語を探す
//   file.write         … ファイルを書く・直す
//   user.ask           … 相談者本人に示して、反応・回答を返す
//   user.message       … 相談者が会話で送ってきた指示（止める指示など）を返す。質問はしない
//   user.notify        … 相談者に示す・一言伝える。返事は待たない
//   browser.screenshot … プロトタイプをブラウザ（Playwright など）で開き、スクリーンショットを撮る・操作して確かめる
//   agent.run          … 別のエージェント（Agent ツール）に作業を任せ、結果を返す
//   web.search         … 公開情報を検索し、見つけたページの URL と中身を手を加えずに返す
// 担当が model で能力を付けた作業は、その能力でファイルを読みながら考える作業を表す。

