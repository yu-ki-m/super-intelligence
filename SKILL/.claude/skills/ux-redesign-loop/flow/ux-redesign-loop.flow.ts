// 新しい版のファイルを書き、版の記録に一行足す。前の版のファイルは書き換えない
async function 版を足す(保存先: string, 案: string, 新しい版: 版, 元にした版: 版 | null, 段: string, 変えたこと: string, 内容: string): Promise<void> {
  await 書く(新しい版.パス, 内容);
  await 書く(`${保存先}/04_プロトタイプの版.md`, `${案} v${新しい版.番号}（${段}）：元にした版 ${元にした版 === null ? "なし" : "v" + 元にした版.番号}。${変えたこと}`);
}

