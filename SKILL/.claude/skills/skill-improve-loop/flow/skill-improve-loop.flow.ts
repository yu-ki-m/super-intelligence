        "起動時に4つを確かめる。既定を示し、そのままでよければ「既定で」と答えてもらう：①ループ内で使うスキル（既定：skill-creator。別のスキルの名前か「使わない」も選べる）、②反復の上限回数（深さの既定の値。上限として扱うか、その回数まで続けるか）、③本物のスキルへの反映の方法（写しで直し最後に反映／本物を直接直す／写しだけ渡す）と、新規スキルならその反映先（作業フォルダの .claude/skills か ~/.claude/skills か）、④予算（テストの実行回数とトークン数の上限。1回の反復で使う見込み：ケースの数×構成の数×試作する案の数）。設計フォルダが長ければ、260文字の上限に触れうることを伝え、短い場所を勧める",
